#!/usr/bin/env node
// Turns the JSON Schema `loco-protocol` derives for ServerMsg into Valibot.
//
// Run by server-rs/crates/protocolgen (`make protocol`), which pipes the
// schema in on stdin and writes what this prints to
// client/src/types/protocolSchemas.ts. It can also be pointed at a file:
// `node tools/protocol/valibot.mjs schema.json`.
//
// It understands exactly the constructions the protocol uses and refuses
// everything else, naming the path it stopped at. That is the point of it: a
// validator that guessed at a keyword it did not know would accept or refuse
// messages for a reason nobody wrote down, and the way that fails is silent.
// A refusal stops `make protocol` and the CI check instead, and the fix is a
// decision in the Rust types or a rule added here, in the open.
//
// What it accepts:
// - `$ref` to `#/$defs/<Name>` -> the named schema constant;
// - a string `enum`, or a `oneOf` of string `const`s -> `v.picklist`;
// - `string`, `boolean`, `integer` (`format` int32 / int64 is an annotation in
//   draft 2020-12, so it is read and not enforced), `array` with `items`;
// - `object` with `properties` and `required`: a property not required is
//   `v.optional`. No `additionalProperties` means extra keys are allowed, which
//   is what `v.object` does; `false` is `v.strictObject`;
// - at the root, a `oneOf` of tagged variants, each a `$ref` to an object
//   schema plus `properties.type.const` -> `v.variant('type', ...)`;
// - `description` and `title` anywhere, as comments.
//
// Deliberately dependency-free: it runs before `npm ci` in CI.

import { readFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const HEADER = `// Code generated by server-rs/crates/protocolgen. DO NOT EDIT.
//
// Source: server-rs/crates/loco-protocol. Regenerate with "make protocol"; CI
// fails the build if this file and the Rust source have drifted apart, so
// editing it by hand is undone by the next run rather than merged.
//
// This file carries the inbound validation schemas.
`

const ANNOTATIONS = new Set(['description', 'title'])

class Refusal extends Error {}

function refuse(path, what) {
  throw new Refusal(`${path}: ${what}`)
}

function keysBesides(schema, allowed) {
  return Object.keys(schema).filter((k) => !allowed.has(k) && !ANNOTATIONS.has(k))
}

function only(schema, path, ...allowed) {
  const extra = keysBesides(schema, new Set(allowed))
  if (extra.length) refuse(path, `cannot express ${extra.map((k) => `"${k}"`).join(', ')} here`)
}

/** CardDTO -> cardSchema, ServerMsg -> serverMsgSchema: the hand-written file's convention. */
export function schemaName(defName) {
  const base = defName.endsWith('DTO') ? defName.slice(0, -3) : defName
  if (!/^[A-Z][A-Za-z0-9]*$/.test(base)) throw new Refusal(`$defs/${defName}: not a type name`)
  return base[0].toLowerCase() + base.slice(1) + 'Schema'
}

function refName(ref, path) {
  const m = /^#\/\$defs\/([A-Za-z0-9]+)$/.exec(ref)
  if (!m) refuse(path, `$ref ${JSON.stringify(ref)} does not name a definition`)
  return m[1]
}

function quote(s) {
  return `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

function comment(text, indent) {
  if (!text || !text.trim()) return ''
  return text
    .split('\n')
    .map((line) => (line ? `${indent}// ${line}` : `${indent}//`))
    .join('\n') + '\n'
}

function stringConsts(entries) {
  return (
    Array.isArray(entries) &&
    entries.length > 0 &&
    entries.every(
      (e) =>
        e &&
        typeof e === 'object' &&
        typeof e.const === 'string' &&
        e.type === 'string' &&
        keysBesides(e, new Set(['const', 'type'])).length === 0,
    )
  )
}

function picklist(values, indent) {
  const inner = values.map((v) => `${indent}  ${quote(v)},`).join('\n')
  return `v.picklist([\n${inner}\n${indent}])`
}

function isInteger(schema, path) {
  if (schema.format !== undefined && schema.format !== 'int32' && schema.format !== 'int64') {
    refuse(path, `integer format ${JSON.stringify(schema.format)}`)
  }
  return true
}

/** One schema as a Valibot expression. `deps` collects the definitions it names. */
function expr(schema, path, indent, deps) {
  if (schema === null || typeof schema !== 'object' || Array.isArray(schema)) {
    refuse(path, 'a schema must be an object')
  }
  if ('$ref' in schema) {
    only(schema, path, '$ref')
    const name = refName(schema.$ref, path)
    deps.add(name)
    return schemaName(name)
  }
  if ('oneOf' in schema) {
    only(schema, path, 'oneOf')
    if (!stringConsts(schema.oneOf)) refuse(path, 'a oneOf that is not a set of string constants')
    return picklist(schema.oneOf.map((e) => e.const), indent)
  }
  if ('enum' in schema) {
    only(schema, path, 'enum', 'type')
    if (schema.type !== 'string' || !schema.enum.every((e) => typeof e === 'string')) {
      refuse(path, 'an enum that is not all strings')
    }
    return picklist(schema.enum, indent)
  }
  if ('const' in schema) {
    only(schema, path, 'const', 'type')
    if (typeof schema.const !== 'string' || schema.type !== 'string') refuse(path, 'a non-string const')
    return `v.literal(${quote(schema.const)})`
  }
  if (Array.isArray(schema.type)) {
    refuse(path, `a union of types ${JSON.stringify(schema.type)} (a nullable required field?)`)
  }
  switch (schema.type) {
    case 'string':
      only(schema, path, 'type')
      return 'v.string()'
    case 'boolean':
      only(schema, path, 'type')
      return 'v.boolean()'
    case 'integer':
      only(schema, path, 'type', 'format')
      isInteger(schema, path)
      return 'v.pipe(v.number(), v.integer())'
    case 'array':
      only(schema, path, 'type', 'items')
      if (!schema.items) refuse(path, 'an array with no items schema')
      return `v.array(${expr(schema.items, `${path}/items`, indent, deps)})`
    case 'object':
      return objectExpr(schema, path, indent, deps, [])
    case undefined:
      refuse(path, `cannot express a schema made of ${Object.keys(schema).map((k) => `"${k}"`).join(', ')}`)
      break
    default:
      refuse(path, `type ${JSON.stringify(schema.type)}`)
  }
}

/** An object schema; `prefix` is lines written before its own properties. */
function objectExpr(schema, path, indent, deps, prefix) {
  only(schema, path, 'type', 'properties', 'required', 'additionalProperties')
  if (schema.additionalProperties !== undefined && schema.additionalProperties !== false) {
    refuse(path, 'additionalProperties other than false')
  }
  const props = schema.properties ?? {}
  const required = new Set(schema.required ?? [])
  for (const r of required) {
    if (!(r in props)) refuse(path, `"${r}" is required but has no schema`)
  }
  const lines = [...prefix]
  for (const [key, sub] of Object.entries(props)) {
    if (!/^[a-z_][a-z0-9_]*$/.test(key)) refuse(`${path}/properties/${key}`, 'not a plain field name')
    const e = expr(sub, `${path}/properties/${key}`, indent + '  ', deps)
    lines.push(
      comment(sub.description, indent + '  ') +
        `${indent}  ${key}: ${required.has(key) ? e : `v.optional(${e})`},`,
    )
  }
  const ctor = schema.additionalProperties === false ? 'v.strictObject' : 'v.object'
  return `${ctor}({\n${lines.join('\n')}\n${indent}})`
}

/** The root: a oneOf of `type`-tagged variants, each a $ref plus its tag. */
function variantExpr(root, defs, deps) {
  const path = '#'
  if (!Array.isArray(root.oneOf)) refuse(path, 'the root is not a oneOf of tagged variants')
  const tags = []
  const arms = root.oneOf.map((arm, i) => {
    const at = `#/oneOf/${i}`
    only(arm, at, '$ref', 'type', 'properties', 'required')
    if (arm.type !== 'object') refuse(at, 'a variant that is not an object')
    const tag = arm.properties?.type
    if (!tag || tag.type !== 'string' || typeof tag.const !== 'string') {
      refuse(at, 'a variant without a string `type` constant')
    }
    only(tag, `${at}/properties/type`, 'type', 'const')
    if (Object.keys(arm.properties).length !== 1) refuse(at, 'a variant with fields beside its payload')
    if (JSON.stringify(arm.required) !== '["type"]') refuse(at, 'a variant whose tag is not required')
    if (tags.includes(tag.const)) refuse(at, `the tag ${tag.const} twice`)
    tags.push(tag.const)

    const prefix = []
    if (arm.$ref) {
      const name = refName(arm.$ref, at)
      const payload = defs[name]
      if (!payload || payload.type !== 'object') refuse(at, `${name} is not an object schema`)
      if (payload.properties && 'type' in payload.properties) refuse(at, `${name} has its own "type" field`)
      if (payload.additionalProperties === false) refuse(at, `${name} is strict, and a tag would be extra`)
      deps.add(name)
      prefix.push(`      ...${schemaName(name)}.entries,`)
    }
    prefix.push(`      type: v.literal(${quote(tag.const)}),`)
    return comment(arm.description, '  ') + `  v.object({\n${prefix.join('\n')}\n    }),`
  })
  return { tags, body: `v.variant('type', [\n${arms.join('\n')}\n])` }
}

export function convert(root) {
  if (root === null || typeof root !== 'object') throw new Refusal('#: not a schema')
  only(root, '#', '$schema', '$defs', 'oneOf')
  if (root.$schema !== 'https://json-schema.org/draft/2020-12/schema') {
    refuse('#', `$schema ${JSON.stringify(root.$schema)}: only draft 2020-12 is read`)
  }
  if (root.title !== 'ServerMsg') refuse('#', `title ${JSON.stringify(root.title)}: expected ServerMsg`)
  const defs = root.$defs ?? {}

  // Every definition, then the order that declares each before its first use:
  // these are `const` bindings, and a schema read before its declaration is a
  // temporal-dead-zone crash on the first message rather than a compile error.
  const names = new Set()
  const bodies = new Map()
  const depsOf = new Map()
  for (const [name, schema] of Object.entries(defs)) {
    const n = schemaName(name)
    if (names.has(n) || n === 'serverMsgSchema' || n === 'serverMsgTypeSchema') {
      throw new Refusal(`$defs/${name}: its schema name ${n} is taken`)
    }
    names.add(n)
    const deps = new Set()
    bodies.set(name, expr(schema, `#/$defs/${name}`, '', deps))
    depsOf.set(name, deps)
  }
  const ordered = []
  const state = new Map()
  const visit = (name, from) => {
    if (!defs[name]) throw new Refusal(`${from}: $ref to a missing definition ${name}`)
    if (state.get(name) === 'done') return
    if (state.get(name) === 'open') throw new Refusal(`$defs/${name}: a recursive type cannot be a const`)
    state.set(name, 'open')
    for (const d of depsOf.get(name)) visit(d, `#/$defs/${name}`)
    state.set(name, 'done')
    ordered.push(name)
  }
  for (const name of Object.keys(defs).sort()) visit(name, '#/$defs')

  const rootDeps = new Set()
  const { tags, body } = variantExpr(root, defs, rootDeps)
  for (const d of rootDeps) visit(d, '#')

  let out = HEADER + "\nimport * as v from 'valibot'\n"
  for (const name of ordered) {
    out += '\n' + comment(defs[name].description, '')
    out += `export const ${schemaName(name)} = ${bodies.get(name)}\n`
  }
  out += '\n// Every `type` the server can send.\n'
  out += `export const serverMsgTypeSchema = ${picklist(tags, '')}\n`
  out += '\n' + comment(root.description, '')
  out += `export const serverMsgSchema = ${body}\n`
  return out
}

function main() {
  const file = process.argv[2]
  const text = file ? readFileSync(file, 'utf8') : readFileSync(0, 'utf8')
  try {
    process.stdout.write(convert(JSON.parse(text)))
  } catch (e) {
    if (e instanceof Refusal) {
      process.stderr.write(`valibot.mjs refuses the schema: ${e.message}\n`)
      process.exit(1)
    }
    throw e
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()

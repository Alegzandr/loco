#!/usr/bin/env node
/**
 * The script hashes the CSP header has to allow, read out of the built HTML.
 *
 * nginx sends `script-src 'self'` as a header, and SvelteKit starts its router
 * on a prerendered page with one inline <script>. SvelteKit hashes that script
 * itself (`csp: { mode: 'hash' }` in vite.config.ts) and writes the hash into a
 * `<meta http-equiv>` on the page — but a meta policy does not loosen a header
 * policy: both are enforced, and the header alone would refuse the bootstrap
 * and leave every page blank in production, and only there.
 *
 * So this runs after `vite build` (it is the last step of `npm run build`),
 * hashes every executable inline script in `build/`, checks each one against
 * the meta SvelteKit wrote on the same page, and writes `csp-hashes.conf`: one
 * `set` of the variable `security-headers.conf` splices into `script-src`. The
 * Dockerfile copies it beside that file. It is generated, never committed — a
 * stale copy would refuse the bootstrap of every page it no longer matches.
 *
 * A data block (`application/ld+json`) is not a script to CSP and is skipped.
 * Anything else inline that SvelteKit did not hash fails the build here, which
 * is the one place it can be caught before nginx refuses it.
 *
 * Usage: node scripts/csp-hashes.mjs [buildDir] [outFile]
 */
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const CLIENT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/** Types a browser executes. No type at all is JavaScript. */
const EXECUTABLE = /^(|text\/javascript|application\/javascript|module)$/i

/**
 * Every executable inline script in one document, as the CSP source a header
 * would need to allow it (`'sha256-…'`), hashed over the exact bytes between
 * the tags — which is what a browser hashes.
 *
 * @param {string} html
 * @returns {string[]}
 */
export function inlineScriptHashes(html) {
  const out = []
  const re = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi
  for (let m = re.exec(html); m; m = re.exec(html)) {
    const attrs = m[1]
    if (/\bsrc\s*=/i.test(attrs)) continue
    const type = /\btype\s*=\s*["']?([^"'\s>]*)/i.exec(attrs)?.[1] ?? ''
    if (!EXECUTABLE.test(type)) continue
    out.push(`'sha256-${createHash('sha256').update(m[2], 'utf8').digest('base64')}'`)
  }
  return out
}

/**
 * The script hashes SvelteKit put in the page's own `<meta http-equiv>` policy.
 *
 * @param {string} html
 * @returns {string[]}
 */
export function metaScriptHashes(html) {
  const meta = /<meta http-equiv="content-security-policy" content="([^"]*)"/i.exec(html)?.[1] ?? ''
  const scriptSrc = /(?:^|;)\s*script-src\s+([^;]*)/.exec(meta)?.[1] ?? ''
  return scriptSrc.split(/\s+/).filter((s) => s.startsWith("'sha256-"))
}

/**
 * The nginx include: one variable, every hash the built site needs.
 *
 * @param {string[]} hashes
 * @returns {string}
 */
export function hashesConf(hashes) {
  const sorted = [...new Set(hashes)].sort()
  return (
    '# Generated by client/scripts/csp-hashes.mjs from the built HTML. Do not edit:\n' +
    '# `npm run build` rewrites it, and the Dockerfile copies it beside\n' +
    '# security-headers.conf, which splices it into script-src.\n' +
    `set $loco_script_hashes "${sorted.join(' ')}";\n`
  )
}

/**
 * @param {string} dir
 * @param {string[]} [out]
 * @returns {string[]}
 */
function htmlFiles(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry)
    if (statSync(full).isDirectory()) htmlFiles(full, out)
    else if (entry.endsWith('.html')) out.push(full)
  }
  return out
}

function main() {
  const buildDir = path.resolve(process.argv[2] ?? path.join(CLIENT, 'build'))
  const outFile = path.resolve(process.argv[3] ?? path.join(CLIENT, 'csp-hashes.conf'))
  const all = []
  const problems = []
  for (const file of htmlFiles(buildDir)) {
    const html = readFileSync(file, 'utf8')
    const found = inlineScriptHashes(html)
    const declared = new Set(metaScriptHashes(html))
    for (const hash of found) {
      if (!declared.has(hash)) {
        problems.push(`${path.relative(buildDir, file)}: inline script ${hash} is not in the page's own policy`)
      }
    }
    all.push(...found)
  }
  if (problems.length) {
    console.error(problems.join('\n'))
    process.exit(1)
  }
  writeFileSync(outFile, hashesConf(all))
  console.log(`csp-hashes: ${new Set(all).size} script hash(es) → ${path.relative(process.cwd(), outFile)}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
